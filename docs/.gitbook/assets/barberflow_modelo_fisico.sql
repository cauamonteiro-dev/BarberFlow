/*
===============================================================================
3. TABELA: BARBEARIA
===============================================================================

Representa cada barbearia cadastrada no BarberFlow.

Relacionamentos:
- Uma barbearia possui vários barbeiros.
- Uma barbearia possui vários serviços.
- Uma barbearia possui vários agendamentos.
- Uma barbearia possui vários planos.
- Uma barbearia pode possuir vários vínculos com clientes.

Regras:
- O nome é obrigatório.
- A situação da barbearia é controlada pelo campo "ativa".
*/

CREATE TABLE barbearia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(100) NOT NULL,
    ativa BOOLEAN NOT NULL,

    CONSTRAINT pk_barbearia
        PRIMARY KEY (id)
);


/*
===============================================================================
4. TABELA: CLIENTE
===============================================================================

Representa os clientes do sistema.

Um mesmo cliente pode frequentar mais de uma barbearia. Por isso, o vínculo
entre cliente e barbearia não é armazenado diretamente nesta tabela.

O relacionamento é realizado pela tabela CLIENTE_BARBEARIA.

Regras:
- Nome é obrigatório.
- E-mail, quando informado, deve ser único.
*/

CREATE TABLE cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(100) NOT NULL,
    telefone VARCHAR(20),
    email VARCHAR(120),

    CONSTRAINT pk_cliente
        PRIMARY KEY (id),

    CONSTRAINT uk_cliente_email
        UNIQUE (email)
);


/*
===============================================================================
5. TABELA: CLIENTE_BARBEARIA
===============================================================================

Tabela associativa responsável pelo relacionamento entre CLIENTE e BARBEARIA.

Relacionamento:
- Um cliente pode estar vinculado a várias barbearias.
- Uma barbearia pode possuir vários clientes.

A combinação (cliente_id, barbearia_id) é única para impedir que o mesmo
cliente possua mais de um vínculo com a mesma barbearia.

O campo "status" permite ativar ou inativar o vínculo.

Regra de negócio relacionada:
- RN01: um cliente pode estar vinculado a uma ou mais barbearias.
- RN02: o mesmo cliente não pode possuir mais de um vínculo com a mesma
        barbearia.
*/

CREATE TABLE cliente_barbearia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    cliente_id BIGINT NOT NULL,
    barbearia_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,

    CONSTRAINT pk_cliente_barbearia
        PRIMARY KEY (id),

    CONSTRAINT fk_cliente_barbearia_cliente
        FOREIGN KEY (cliente_id)
        REFERENCES cliente(id),

    CONSTRAINT fk_cliente_barbearia_barbearia
        FOREIGN KEY (barbearia_id)
        REFERENCES barbearia(id),

    CONSTRAINT uk_cliente_barbearia
        UNIQUE (cliente_id, barbearia_id),

    CONSTRAINT ck_cliente_barbearia_status
        CHECK (status IN ('ATIVO', 'INATIVO'))
);


/*
===============================================================================
6. TABELA: BARBEIRO
===============================================================================

Representa os profissionais que trabalham em uma barbearia.

Relacionamento:
- Uma barbearia pode possuir vários barbeiros.
- Cada barbeiro pertence a uma única barbearia.

Regras:
- O barbeiro deve estar vinculado a uma barbearia.
- O nome é obrigatório.
- O status controla se o barbeiro está ativo ou inativo.

Regra de negócio:
- RN03: todo barbeiro deve estar vinculado a uma barbearia.
*/

CREATE TABLE barbeiro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    barbearia_id BIGINT NOT NULL,
    nome VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL,

    CONSTRAINT pk_barbeiro
        PRIMARY KEY (id),

    CONSTRAINT fk_barbeiro_barbearia
        FOREIGN KEY (barbearia_id)
        REFERENCES barbearia(id),

    CONSTRAINT ck_barbeiro_status
        CHECK (status IN ('ATIVO', 'INATIVO'))
);


/*
===============================================================================
7. TABELA: SERVICO
===============================================================================

Representa os serviços oferecidos por cada barbearia.

Exemplos:
- Corte
- Barba
- Corte + Barba

Relacionamento:
- Uma barbearia possui vários serviços.
- Cada serviço pertence a uma única barbearia.

Regras:
- Nome é obrigatório.
- Preço não pode ser negativo.
- Duração deve ser maior que zero.
- O status controla se o serviço está ativo ou inativo.

Regra de negócio:
- RN04: todo serviço deve pertencer a uma barbearia.
- RN08: serviço deve possuir nome, preço e duração.
*/

CREATE TABLE servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    barbearia_id BIGINT NOT NULL,
    nome VARCHAR(100) NOT NULL,
    preco NUMERIC(10,2) NOT NULL,
    duracao_min INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,

    CONSTRAINT pk_servico
        PRIMARY KEY (id),

    CONSTRAINT fk_servico_barbearia
        FOREIGN KEY (barbearia_id)
        REFERENCES barbearia(id),

    CONSTRAINT ck_servico_preco
        CHECK (preco >= 0),

    CONSTRAINT ck_servico_duracao
        CHECK (duracao_min > 0),

    CONSTRAINT ck_servico_status
        CHECK (status IN ('ATIVO', 'INATIVO'))
);


/*
===============================================================================
8. TABELA: PLANO
===============================================================================

Representa os planos oferecidos por uma barbearia aos seus clientes.

Importante:
"Plano" representa um plano comercial oferecido pela barbearia ao cliente.
Não representa uma assinatura da barbearia ao sistema BarberFlow.

Relacionamento:
- Uma barbearia pode possuir vários planos.
- Cada plano pertence a uma única barbearia.

Regras:
- Nome é obrigatório.
- Preço não pode ser negativo.
- O status controla se o plano está ativo ou inativo.

Regra de negócio:
- RN09: todo plano deve pertencer a uma barbearia.
*/

CREATE TABLE plano (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    barbearia_id BIGINT NOT NULL,
    nome VARCHAR(100) NOT NULL,
    preco NUMERIC(10,2) NOT NULL,
    status VARCHAR(20) NOT NULL,

    CONSTRAINT pk_plano
        PRIMARY KEY (id),

    CONSTRAINT fk_plano_barbearia
        FOREIGN KEY (barbearia_id)
        REFERENCES barbearia(id),

    CONSTRAINT ck_plano_preco
        CHECK (preco >= 0),

    CONSTRAINT ck_plano_status
        CHECK (status IN ('ATIVO', 'INATIVO'))
);


/*
===============================================================================
9. TABELA: AGENDAMENTO
===============================================================================

Representa os agendamentos realizados no sistema.

Cada agendamento relaciona:
- uma barbearia;
- um cliente;
- um barbeiro;
- um serviço;
- horário de início;
- horário de término;
- status.

Relacionamentos:
- Uma barbearia possui vários agendamentos.
- Um cliente pode possuir vários agendamentos.
- Um barbeiro pode possuir vários agendamentos.
- Um serviço pode estar presente em vários agendamentos.

Regras:
- Todos os relacionamentos são obrigatórios.
- O horário de término deve ser posterior ao horário de início.
- O status deve representar um estado válido.

Status previstos:
- AGENDADO
- CONFIRMADO
- CONCLUIDO
- CANCELADO

Regras de negócio:
- RN05: o agendamento deve estar associado a barbearia, cliente, barbeiro
        e serviço.
- RN06: o cliente deve estar vinculado à barbearia onde o agendamento
        ocorre.
- RN07: o barbeiro não pode possuir agendamentos conflitantes no mesmo
        período.
*/

CREATE TABLE agendamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    barbearia_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    barbeiro_id BIGINT NOT NULL,
    servico_id BIGINT NOT NULL,
    inicio TIMESTAMP NOT NULL,
    fim TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL,

    CONSTRAINT pk_agendamento
        PRIMARY KEY (id),

    CONSTRAINT fk_agendamento_barbearia
        FOREIGN KEY (barbearia_id)
        REFERENCES barbearia(id),

    CONSTRAINT fk_agendamento_cliente
        FOREIGN KEY (cliente_id)
        REFERENCES cliente(id),

    CONSTRAINT fk_agendamento_barbeiro
        FOREIGN KEY (barbeiro_id)
        REFERENCES barbeiro(id),

    CONSTRAINT fk_agendamento_servico
        FOREIGN KEY (servico_id)
        REFERENCES servico(id),

    CONSTRAINT ck_agendamento_horario
        CHECK (fim > inicio),

    CONSTRAINT ck_agendamento_status
        CHECK (
            status IN (
                'AGENDADO',
                'CONFIRMADO',
                'CONCLUIDO',
                'CANCELADO'
            )
        )
);


/*
===============================================================================
10. RESTRIÇÃO ADICIONAL DO AGENDAMENTO
===============================================================================

Esta FK composta implementa fisicamente a RN06.

Ela garante que a combinação:

    cliente_id + barbearia_id

existente em AGENDAMENTO também exista em CLIENTE_BARBEARIA.

Dessa forma, não é possível criar um agendamento para um cliente que não
possua vínculo cadastrado com aquela barbearia.

A restrição utiliza a UNIQUE(cliente_id, barbearia_id) criada anteriormente
na tabela CLIENTE_BARBEARIA.
*/

ALTER TABLE agendamento
ADD CONSTRAINT fk_agendamento_cliente_barbearia
    FOREIGN KEY (cliente_id, barbearia_id)
    REFERENCES cliente_barbearia (cliente_id, barbearia_id);


/*
===============================================================================
11. TABELA: ASSINATURA
===============================================================================

Representa a assinatura de um plano por um cliente.

Relacionamentos:
- Um cliente pode possuir várias assinaturas ao longo do tempo.
- Um plano pode estar associado a várias assinaturas.

Regras:
- Cliente e plano são obrigatórios.
- Data de início é obrigatória.
- Data de fim pode ser nula enquanto a assinatura estiver vigente.
- Quando informada, a data de fim não pode ser anterior à data de início.

Status previstos:
- ATIVA
- ENCERRADA
- CANCELADA

Regras de negócio:
- RN10: a assinatura relaciona cliente e plano.
- RN11: o cliente deve estar vinculado à barbearia responsável pelo plano
        para possuir uma assinatura daquele plano.
*/

CREATE TABLE assinatura (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    cliente_id BIGINT NOT NULL,
    plano_id BIGINT NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE,
    status VARCHAR(20) NOT NULL,

    CONSTRAINT pk_assinatura
        PRIMARY KEY (id),

    CONSTRAINT fk_assinatura_cliente
        FOREIGN KEY (cliente_id)
        REFERENCES cliente(id),

    CONSTRAINT fk_assinatura_plano
        FOREIGN KEY (plano_id)
        REFERENCES plano(id),

    CONSTRAINT ck_assinatura_periodo
        CHECK (
            data_fim IS NULL
            OR data_fim >= data_inicio
        ),

    CONSTRAINT ck_assinatura_status
        CHECK (
            status IN (
                'ATIVA',
                'ENCERRADA',
                'CANCELADA'
            )
        )
);


