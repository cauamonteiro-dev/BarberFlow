===============================================================================
13. PRINCIPAIS RESTRIÇÕES DE INTEGRIDADE
===============================================================================

PK:
- Identificam unicamente cada registro.

FK:
- Garantem que os relacionamentos apontem para registros existentes.

UNIQUE:
- Evitam duplicidade de e-mail do cliente.
- Evitam duplicidade do vínculo cliente/barbearia.

NOT NULL:
- Garante o preenchimento dos dados essenciais.

CHECK:
- Controla preços não negativos.
- Controla duração positiva.
- Garante horários válidos.
- Controla valores permitidos para status.
- Garante períodos de assinatura válidos.

FK composta:
- Garante que o cliente esteja vinculado à barbearia do agendamento.


