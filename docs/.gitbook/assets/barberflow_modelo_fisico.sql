/*
===============================================================================
17. CONSULTA RELACIONAL DE EXEMPLO
===============================================================================

Consulta para visualizar os agendamentos com informações de cliente,
barbeiro, serviço e barbearia.
*/

SELECT
    a.id AS agendamento_id,
    b.nome AS barbearia,
    c.nome AS cliente,
    br.nome AS barbeiro,
    s.nome AS servico,
    a.inicio,
    a.fim,
    a.status
FROM agendamento a
INNER JOIN barbearia b
    ON b.id = a.barbearia_id
INNER JOIN cliente c
    ON c.id = a.cliente_id
INNER JOIN barbeiro br
    ON br.id = a.barbeiro_id
INNER JOIN servico s
    ON s.id = a.servico_id
ORDER BY a.inicio;


