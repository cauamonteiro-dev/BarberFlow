CREATE TABLE usuario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(100) NOT NULL, email VARCHAR(120) NOT NULL UNIQUE,
 senha_hash VARCHAR(100) NOT NULL, cliente_id BIGINT UNIQUE REFERENCES cliente(id), ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE permissao (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id), barbearia_id BIGINT NOT NULL REFERENCES barbearia(id),
 perfil VARCHAR(20) NOT NULL CHECK(perfil IN ('ADMIN','BARBEIRO')),
 barbeiro_id BIGINT REFERENCES barbeiro(id), UNIQUE(usuario_id,barbearia_id,perfil),
 CHECK ((perfil='BARBEIRO' AND barbeiro_id IS NOT NULL) OR (perfil='ADMIN' AND barbeiro_id IS NULL))
);
CREATE TABLE expediente (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 barbeiro_id BIGINT NOT NULL REFERENCES barbeiro(id), dia_semana INTEGER NOT NULL CHECK(dia_semana BETWEEN 1 AND 7),
 inicio TIME NOT NULL, fim TIME NOT NULL, CHECK(fim>inicio), UNIQUE(barbeiro_id,dia_semana,inicio)
);
CREATE TABLE bloqueio (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 barbeiro_id BIGINT NOT NULL REFERENCES barbeiro(id), inicio TIMESTAMP NOT NULL, fim TIMESTAMP NOT NULL,
 motivo VARCHAR(200) NOT NULL, CHECK(fim>inicio)
);
